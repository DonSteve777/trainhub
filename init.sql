-- Vista: Posts con conteo de likes
CREATE OR REPLACE VIEW "posts_with_likes" AS
SELECT 
  p.*,
  COALESCE(COUNT(l."post_id"), 0) AS likes_count
FROM "posts" p
LEFT JOIN "Likes" l ON p."id" = l."post_id"
GROUP BY p."id";

-- Vista: Conversaciones con último mensaje (adaptada a estructura sin tabla Conversations)
-- Esta vista agrupa mensajes por pares de usuarios y muestra el último mensaje de cada conversación
CREATE OR REPLACE VIEW "conversations_summary" AS
WITH normalized_conversations AS (
  SELECT 
    CASE 
      WHEN "sender_id" < "receiver_id" 
      THEN "sender_id"
      ELSE "receiver_id"
    END AS "user_a_id",
    CASE 
      WHEN "sender_id" < "receiver_id" 
      THEN "receiver_id"
      ELSE "sender_id"
    END AS "user_b_id",
    "id",
    "content",
    "send_date",
    "status",
    "sender_id",
    "receiver_id",
    ROW_NUMBER() OVER (
      PARTITION BY 
        CASE 
          WHEN "sender_id" < "receiver_id" 
          THEN ("sender_id", "receiver_id")
          ELSE ("receiver_id", "sender_id")
        END
      ORDER BY "send_date" DESC
    ) AS rn
  FROM "Messages"
)
SELECT 
  "user_a_id",
  "user_b_id",
  "id" AS "last_message_id",
  "content" AS "last_message_content",
  "send_date" AS "last_message_date",
  "status" AS "last_message_status",
  "sender_id" AS "last_message_sender_id",
  "receiver_id" AS "last_message_receiver_id"
FROM normalized_conversations
WHERE rn = 1;

