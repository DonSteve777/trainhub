-- ============================================================================
-- 1. CREACIÓN DE BASE DE DATOS Y USUARIOS
-- ============================================================================

CREATE DATABASE trainhub_dev_db OWNER postgres;

CREATE ROLE dev_user WITH LOGIN PASSWORD 'dev_pass';

-- Conectarse a la base antes de dar permisos de esquema
\connect trainhub_dev_db

-- Permisos sobre el esquema público
GRANT USAGE, CREATE ON SCHEMA public TO dev_user;

-- Permisos sobre las tablas y secuencias existentes
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO dev_user;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO dev_user;

-- Para que las tablas que se crean después también hereden permisos automáticamente
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO dev_user;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO dev_user;

-- Ajustar el search_path (para que use 'public' por defecto)
ALTER ROLE dev_user SET search_path TO public;

-- ============================================================================
-- 2. CREACIÓN DE TIPOS ENUM
-- ============================================================================

CREATE TYPE account_status_enum AS ENUM ('PENDING_CONFIRMATION', 'ACTIVE', 'BLOCKED');
CREATE TYPE friendship_status_enum AS ENUM ('PENDING', 'FRIEND', 'BLOCKED');
CREATE TYPE message_status_enum AS ENUM ('SENDING', 'SENT', 'DELIVERED', 'READ');

-- ============================================================================
-- 3. CREACIÓN DE TABLAS
-- ============================================================================

-- Tabla: users
CREATE TABLE "users" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" VARCHAR(60) NOT NULL,
  "email" VARCHAR(255) UNIQUE NOT NULL,
  "password_hash" VARCHAR(255) NOT NULL,
  "bio" TEXT,
  "photo_url" VARCHAR(255),
  "account_status" account_status_enum NOT NULL,
  "email_verified" BOOLEAN DEFAULT false,
  "registration_date" TIMESTAMP DEFAULT (now()),
  "last_login" TIMESTAMP,
  -- Constraints de validación
  CONSTRAINT chk_users_name_length CHECK (LENGTH("name") >= 2 AND LENGTH("name") <= 60),
  CONSTRAINT chk_users_bio_length CHECK ("bio" IS NULL OR LENGTH("bio") <= 280),
  CONSTRAINT chk_users_account_status CHECK ("account_status" IN ('PENDING_CONFIRMATION', 'ACTIVE', 'BLOCKED'))
);

-- Tabla: Refresh_Tokens
CREATE TABLE "Refresh_Tokens" (
  "token_hash" VARCHAR(255) PRIMARY KEY,
  "user_id" INT NOT NULL,
  "expiration_date" TIMESTAMP NOT NULL,
  "revoked" BOOLEAN DEFAULT false,
  "creation_date" TIMESTAMP DEFAULT (now())
);

-- Tabla: posts
CREATE TABLE "posts" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" INT NOT NULL,
  "r1_time" VARCHAR(5) NOT NULL,
  "r2_time" VARCHAR(5) NOT NULL,
  "r3_time" VARCHAR(5) NOT NULL,
  "r4_time" VARCHAR(5) NOT NULL,
  "r5_time" VARCHAR(5) NOT NULL,
  "r6_time" VARCHAR(5) NOT NULL,
  "r7_time" VARCHAR(5) NOT NULL,
  "r8_time" VARCHAR(5) NOT NULL,
  "w1_time" VARCHAR(5) NOT NULL,
  "w2_time" VARCHAR(5) NOT NULL,
  "w3_time" VARCHAR(5) NOT NULL,
  "w4_time" VARCHAR(5) NOT NULL,
  "w5_time" VARCHAR(5) NOT NULL,
  "w6_time" VARCHAR(5) NOT NULL,
  "w7_time" VARCHAR(5) NOT NULL,
  "w8_time" VARCHAR(5) NOT NULL,
  "total_time" VARCHAR(7) NOT NULL,
  "creation_date" TIMESTAMP NOT NULL DEFAULT (now()),
  -- Constraints de validación
  CONSTRAINT chk_posts_total_time_format CHECK (
    "total_time" ~ '^[0-9]{1,2}:[0-5][0-9]:[0-5][0-9]$' OR
    "total_time" ~ '^[0-9]{1,2}:[0-5][0-9]$'
  )
);

-- Tabla: friendships
CREATE TABLE "friendships" (
  "user_a_id" INT NOT NULL,
  "user_b_id" INT NOT NULL,
  "status" friendship_status_enum NOT NULL,
  "relationship_start_date" TIMESTAMP DEFAULT (now()),
  PRIMARY KEY ("user_a_id", "user_b_id"),
  -- Constraint para garantizar user_a_id < user_b_id (se valida con trigger)
  CONSTRAINT chk_friendships_user_order CHECK ("user_a_id" < "user_b_id")
);

-- Tabla: Likes
CREATE TABLE "Likes" (
  "user_id" INT NOT NULL,
  "post_id" INT NOT NULL,
  "like_date" TIMESTAMP DEFAULT (now()),
  PRIMARY KEY ("user_id", "post_id")
);

-- Tabla: Messages
CREATE TABLE "Messages" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "sender_id" INT NOT NULL,
  "receiver_id" INT NOT NULL,
  "content" VARCHAR(2000) NOT NULL,
  "send_date" TIMESTAMP DEFAULT (now()),
  "read_at" TIMESTAMP DEFAULT (now()),
  "status" message_status_enum NOT NULL,
  -- Constraints de validación
  CONSTRAINT chk_messages_sender_receiver CHECK ("sender_id" != "receiver_id"),
  CONSTRAINT chk_messages_content_not_empty CHECK (LENGTH(TRIM("content")) > 0)
);

