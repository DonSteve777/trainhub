-- ============================================================================
-- 7. TRIGGERS
-- ============================================================================

-- Trigger: Validar y normalizar user_a_id < user_b_id en friendships
CREATE OR REPLACE FUNCTION validate_friendship_order()
RETURNS TRIGGER AS $$
BEGIN
  -- Si user_a_id > user_b_id, intercambiar valores
  IF NEW."user_a_id" > NEW."user_b_id" THEN
    DECLARE
      temp_id INT;
    BEGIN
      temp_id := NEW."user_a_id";
      NEW."user_a_id" := NEW."user_b_id";
      NEW."user_b_id" := temp_id;
    END;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_friendships_validate_order
  BEFORE INSERT OR UPDATE ON "friendships"
  FOR EACH ROW
  EXECUTE FUNCTION validate_friendship_order();

-- Trigger: Actualizar read_at cuando status cambia a READ
CREATE OR REPLACE FUNCTION update_message_read_at()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW."status" = 'READ' AND (OLD."status" IS NULL OR OLD."status" != 'READ') THEN
    NEW."read_at" := NOW();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_messages_update_read_at
  BEFORE UPDATE ON "Messages"
  FOR EACH ROW
  EXECUTE FUNCTION update_message_read_at();

