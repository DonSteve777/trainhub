-- Este script crea la base de datos, usuarios, tablas, índices, constraints,
-- triggers y vistas necesarias para el sistema TrainHub.
--
-- Uso:
--   docker exec -it trainhub-postgres-1 psql -U postgres
--   docker exec -i trainhub-postgres-1 psql -U postgres -d postgres < ./init.sql
