package com.trainhub.backend.enums;

/**
 * Enum que representa los roles posibles de un usuario.
 */
public enum Role {
    /**
     * Rol por defecto de cualquier usuario registrado.
     */
    USER,

    /**
     * Rol de administrador de un box, con permisos para publicar contenido del box.
     */
    BOX_ADMIN
}
